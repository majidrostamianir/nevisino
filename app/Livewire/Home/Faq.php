    public $popularQuestions = [0, 1, 4];

    public function toggleQuestion($index)
    {
        if ($this->openIndex === $index) {
            $this->openIndex = null;
        } else {
            $this->openIndex = $index;
        }
    }

    public function setCategory($category)
    {
        $this->activeCategory = $category;
        $this->openIndex = null; // بستن همه سوالات با تغییر دسته
    }

    public function getFilteredFaqsProperty()
    {
        $faqs = $this->allFaqs;

        // فیلتر بر اساس دسته
        if ($this->activeCategory !== 'all') {
            $faqs = array_filter($faqs, function ($faq) {
                return $faq['category'] === $this->activeCategory;
            });
        }

        // فیلتر بر اساس جستجو
        if (!empty(trim($this->searchTerm))) {
            $search = mb_strtolower(trim($this->searchTerm));
            $faqs = array_filter($faqs, function ($faq) use ($search) {
                return mb_strpos(mb_strtolower($faq['question']), $search) !== false ||
                    mb_strpos(mb_strtolower(strip_tags($faq['answer'])), $search) !== false;
            });
        }

        return array_values($faqs);
    }

    public function getCategoryCountsProperty()
    {
        $counts = ['all' => count($this->allFaqs)];
        foreach ($this->allFaqs as $faq) {
            $counts[$faq['category']] = ($counts[$faq['category']] ?? 0) + 1;
        }
        return $counts;
    }

    public function render()
    {
        return view('livewire.home.faq', [
            'faqs' => $this->filteredFaqs,
            'categoryCounts' => $this->categoryCounts,
        ])->title('سوالات متداول | نویسینو');
    }
